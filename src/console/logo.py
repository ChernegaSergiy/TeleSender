def get_version() -> str:
    """Get version from pyproject.toml."""
    try:
        with open('pyproject.toml', 'r', encoding='utf-8') as f:
            content = f.read()

        match = re.search(r'version\s*=\s*["\']([^"\']+)["\']', content)
        if match:
            return match.group(1)
    except Exception:
        pass

    return '1.0.0'


def get_logo(show_version: bool = True) -> str:
    """Get full logo with version footer."""
    if not show_version:
        return LOGO_ART

    title = f"TeleSender · v{get_version()}"
    width = 34
    title = title[:width]
    left = (width - len(title)) // 2
    right = width - len(title) - left

    footer = f"""
    ╔{'═' * width}╗
    ║{' ' * left}{title}{' ' * right}║
    ╚{'═' * width}╝
"""

    return LOGO_ART + footer


def show_logo():
    """Print logo to console."""
    print(get_logo())
